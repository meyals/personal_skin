"""
=============================================================================
קובץ: run.py
שייך ל: צד שרת (Server-Side) — נקודת כניסה לפיתוח
=============================================================================
תפקיד הקובץ:
    נקודת הכניסה (Entry Point) להפעלת שרת ה-Web (Flask) בסביבת פיתוח.
    מריצים אותו מהטרמינל: py -3 run.py

    חשוב: חובה להריץ גם את שרת האימות TCP בטרמינל נפרד!
           py -3 run_auth_server.py

    הגדרות:
    - debug=True → טעינה מחדש אוטומטית + הודעות שגיאה מפורטות
    - host="0.0.0.0" → מאפשר גישה ממחשב אחר ברשת (למשל לבחינה)
    - port=5000 → פורט ברירת מחדל
=============================================================================
"""
import os

from app import create_app

# ─── יצירת אפליקציית Flask ───────────────────────────────────────────────────
# create_app = App Factory — יוצר ומגדיר את כל האפליקציה
app = create_app(os.getenv("FLASK_CONFIG", "development"))

if __name__ == "__main__":
    # 0.0.0.0 = מאזין מכל כתובת IP (כולל ממחשב אחר ברשת)
    # 127.0.0.1 = רק מהמחשב המקומי
    web_host = os.getenv("FLASK_RUN_HOST", "0.0.0.0")
    web_port = int(os.getenv("FLASK_RUN_PORT", "5000"))
    app.run(debug=True, host=web_host, port=web_port)
