"""
=============================================================================
קובץ: auth/validation.py
שייך ל: צד שרת (Server-Side)
=============================================================================
תפקיד הקובץ:
    ולידציה (בדיקה) של חוזק סיסמה. הקובץ מכיל פונקציה אחת שבודקת
    האם הסיסמה שהמשתמש הזין עומדת בדרישות האבטחה.

    הפונקציה משמשת בשני מקומות:
    1. בטפסי Flask (auth/routes.py) — לפני שליחה לשרת הסוקטים
    2. בשרת הסוקטים (socket_auth/handlers.py) — בדיקה נוספת בצד השרת

    כללי סיסמה:
    - מינימום 8 תווים (אורך מינימלי סביר לאבטחה)
    - לפחות אות אחת באנגלית (A-Z או a-z)
    - לפחות ספרה אחת (0-9)
    - לפחות תו מיוחד אחד (!, @, #, $ וכו')

    למה דורשים סיסמה חזקה?
    סיסמה חלשה (כמו "123456") ניתנת לפריצה תוך שניות
    באמצעות התקפת brute force (ניסיון של כל הצירופים).
    ככל שהסיסמה מגוונת ומורכבת יותר, כך קשה יותר לפרוץ.
=============================================================================
"""
from __future__ import annotations

import re


def password_strength_error(password: str) -> str | None:
    """בודק חוזק סיסמה ומחזיר הודעת שגיאה בעברית אם לא תקינה.

    הפונקציה בודקת 4 כללים ומחזירה את ההודעה של הכלל הראשון שנכשל.
    אם כל הכללים עוברים — מחזירה None (הסיסמה תקינה).

    Args:
        password: הסיסמה לבדיקה

    Returns:
        הודעת שגיאה בעברית אם לא תקין, או None אם הסיסמה תקינה.

    דוגמאות:
        password_strength_error("abc")      → "הסיסמה חייבת להכיל לפחות 8 תווים."
        password_strength_error("abcdefgh") → "הסיסמה חייבת להכיל לפחות מספר אחד."
        password_strength_error("Abc12345!") → None  (תקין!)
    """
    value = password or ""

    # כלל 1: אורך מינימלי
    if len(value) < 8:
        return "הסיסמה חייבת להכיל לפחות 8 תווים."

    # כלל 2: לפחות אות אחת באנגלית
    # re.search = חיפוש תבנית (regex) בתוך מחרוזת
    # [A-Za-z] = כל אות באנגלית (גדולה או קטנה)
    if not re.search(r"[A-Za-z]", value):
        return "הסיסמה חייבת להכיל לפחות אות אחת באנגלית."

    # כלל 3: לפחות ספרה אחת
    # \d = כל ספרה (0-9)
    if not re.search(r"\d", value):
        return "הסיסמה חייבת להכיל לפחות מספר אחד."

    # כלל 4: לפחות תו מיוחד אחד
    # [^A-Za-z0-9] = כל תו שהוא לא אות ולא ספרה (!, @, #, $ וכו')
    if not re.search(r"[^A-Za-z0-9]", value):
        return "הסיסמה חייבת להכיל לפחות תו מיוחד אחד."

    # כל הכללים עברו — הסיסמה תקינה
    return None
